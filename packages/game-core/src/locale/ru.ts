import type { ThemeId } from '../themes';

/** Тексты темы: показываются тостом на поле (≤ 21 символа). */
export interface ThemeText {
  /** В начале игры дубля. */
  intro?: string;
  /** Изнанка включилась / выключилась (themes.ts › twist). */
  twistOn?: string;
  twistOff?: string;
  /** Свои названия команд «Море волнуется» (в изнанке — twistCrowd), как их показывает облик темы. */
  crowd?: Partial<Record<'freeze' | 'jump' | 'dance', string>>;
  twistCrowd?: Partial<Record<'freeze' | 'jump' | 'dance', string>>;
  /** Тема с рассудком: подпись при переходе в стадию 0–3 (sanity.ts › sanityStage) и «вырезан на нуле». */
  sanity?: [string, string, string, string];
  sanityLost?: string;
  /** Вырезан Лешим: шевельнулся в его стоп-кадр. */
  leshyTook?: string;
  /** Своя провинность (не повторил жест) и «следующая — последняя»: только у себя на экране. */
  sinned?: string;
  doomed?: string;
  /** Тема с рассудком: чем кончился дубль — остался один, рассвет (живых несколько), сгинули все. */
  ends?: { last: string; dawn: string; none: string };
  /** Вторая подсказка после `intro` (в начале дубля). */
  hint?: string;
  /** Свой триумф победителя матча (вместо «Ты звезда!»): у себя, у других, подпись. */
  triumph?: { you: string; other: string; sub: string };
}

/** Формы множественного числа по Intl.PluralRules: one / few / many / other. */
export interface Plural {
  one: string;
  few?: string;
  many?: string;
  other: string;
}

