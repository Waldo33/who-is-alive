/**
 * «Условия съёмки» — правило на один дубль, со второго дубля матча (первый — обычный, чтобы
 * разогреться). Объявляется на «Мотор!»; индекс уходит в сеть — новые только в конец списка.
 *
 * - hard   «Жёсткий дубль»: не повторил названный жест (не нажал или нажал не тот) — вырезан;
 * - onehit «Один удар»: у каждого один удар вместо трёх;
 * - stars  «Звездопад»: звёзд на поле больше, появляются вдвое быстрее;
 * - rush   «Шквал команд»: «Море волнуется» вдвое чаще, «Толпа решает» — чаще.
 */
export type RoundModId = 'none' | 'hard' | 'onehit' | 'stars' | 'rush';

export const ROUND_MODS: readonly RoundModId[] = ['none', 'hard', 'onehit', 'stars', 'rush'];

export function roundMod(i: number): RoundModId {
  return ROUND_MODS[i] ?? 'none';
}
